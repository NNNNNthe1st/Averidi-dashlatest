import {test} from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {NextRequest} from 'next/server';
import {dashboardDb as db} from '../src/server/db';
import {POST as signup} from '../src/app/api/auth/signup/route';
import {POST as verify} from '../src/app/api/auth/verify/route';
import {POST as login} from '../src/app/api/auth/password-login/route';
import {POST as reset} from '../src/app/api/auth/password-reset/route';
import {GET as workspaces,POST as createWorkspace} from '../src/app/api/workspaces/route';
import {proxy} from '../src/proxy';
import {getAuthenticatedDashboardActor} from '../src/server/auth-boundary';
import {workspaceDashboardEntitlement,evaluateDashboardTrial} from '../src/features/subscriptions/entitlements';
import {requireWorkspaceRole} from '../src/server/workspace-access';

test('standalone signup, verification, session, trial workspace, isolation and recovery',async()=>{
 assert.ok(new URL(process.env.DASHBOARD_DATABASE_URL??'').pathname.endsWith('_test'),'Use a dedicated *_test database');
 const saved={...process.env},originalFetch=globalThis.fetch;
 const origin='https://onboarding-test-codespace-3000.app.github.dev';
 const emails:{to:string[];text:string}[]=[];
 let emailFailure=false;
 Object.assign(process.env,{NODE_ENV:'development',CODESPACES:'true',CODESPACE_NAME:'onboarding-test-codespace',GITHUB_CODESPACES_PORT_FORWARDING_DOMAIN:'app.github.dev',DASHBOARD_DEVELOPMENT_CODESPACES:'true',DASHBOARD_PUBLIC_ORIGIN:origin,DASHBOARD_PUBLIC_URL:origin,DASHBOARD_EMAIL_API_KEY:'re_test_fixture',DASHBOARD_EMAIL_FROM:'Averidi <support@averidi.com>',DASHBOARD_SESSION_SECRET:'isolated-onboarding-test-secret-'.repeat(3),DASHBOARD_RELEASE_MODE:'GENERAL',DASHBOARD_BETA_WORKSPACE_IDS:'',DASHBOARD_RATE_LIMIT_AUTH_PER_MINUTE:'100000',DASHBOARD_RATE_LIMIT_API_PER_MINUTE:'100000'});
 globalThis.fetch=async(input,init)=>{
  assert.equal(String(input),'https://api.resend.com/emails','No external network in this test');
  if(emailFailure)return new Response('{}',{status:503});
  emails.push(JSON.parse(String(init?.body)));return Response.json({id:'fixture'});
 };
 const request=(path:string,body?:unknown,cookie?:string)=>new NextRequest(origin+'/dashboard/app'+path,{method:body===undefined?'GET':'POST',headers:{origin:'https://localhost:3000',referer:origin+'/dashboard/app/signup','sec-fetch-site':'same-origin','content-type':'application/json',...(cookie?{cookie}:{})},...(body===undefined?{}:{body:JSON.stringify(body)})});
 const call=async(path:string,handler:(r:Request)=>Promise<Response>,body?:unknown,cookie?:string)=>{
  const req=request(path,body,cookie),boundary=await proxy(req);
  assert.equal(boundary.headers.get('x-middleware-next'),'1','Proxy must admit '+path+' (status '+boundary.status+')');
  return handler(req);
 };
 const suffix=randomUUID(),email='owner-'+suffix+'@example.test',password='A-valid-test-password-123';
 const ids:string[]=[],workspaceIds:string[]=[];
 try{
  assert.equal((await call('/api/auth/signup',signup,{name:'Test Owner',email,password})).status,201);
  const user=await db.dashboardUser.findUniqueOrThrow({where:{email}});ids.push(user.id);
  assert.equal(user.emailVerifiedAt,null);
  assert.equal((await call('/api/auth/password-login',login,{email,password})).status,403);
  const token=new URL(emails[0].text.split('\n').at(-1)!).searchParams.get('token');
  assert.ok(token);assert.ok(emails[0].text.includes(origin+'/dashboard/app/verify?'));
  assert.equal((await call('/api/auth/verify',verify,{token})).status,200);
  assert.equal((await call('/api/auth/verify',verify,{token})).status,200,'Verification retry is idempotent');
  assert.equal((await call('/api/auth/verify',verify,{token:'invalid'})).status,400);
  const expired=randomUUID().replaceAll('-','').repeat(2);const {tokenHash}=await import('../src/server/local-credentials');
  await db.dashboardCredentialToken.create({data:{userId:user.id,kind:'VERIFY',tokenHash:tokenHash(expired),expiresAt:new Date(0)}});
  assert.equal((await call('/api/auth/verify',verify,{token:expired})).status,400);
  assert.equal((await call('/api/auth/signup',signup,{name:'Test Owner',email,password})).status,409);
  assert.equal((await call('/api/auth/password-login',login,{email,password:'incorrect'})).status,401);
  const signedIn=await call('/api/auth/password-login',login,{email,password});assert.equal(signedIn.status,200);
  const cookie=signedIn.headers.get('set-cookie')!.split(';')[0];
  assert.match(signedIn.headers.get('set-cookie')!,/Secure/);assert.match(signedIn.headers.get('set-cookie')!,/HttpOnly/);
  const actor=await getAuthenticatedDashboardActor(request('/api/workspaces',undefined,cookie));assert.equal(actor?.userId,user.id);
  assert.equal((await call('/api/workspaces',workspaces,undefined,cookie)).status,200);
  const created=await call('/api/workspaces',createWorkspace,{name:'Trial Business'},cookie);assert.equal(created.status,201);
  const workspace=(await created.json()).workspace;workspaceIds.push(workspace.id);
  assert.equal((await proxy(request('/api/workspaces/'+workspace.id))).headers.get('x-middleware-next'),'1');
  assert.equal((await workspaceDashboardEntitlement(actor!,workspace.id))?.planCode,'TRIAL');
  const stored=await db.dashboardWorkspace.findUniqueOrThrow({where:{id:workspace.id}});
  assert.equal(stored.trialStartedAt!.toISOString(),user.createdAt.toISOString());
  const listed=await (await call('/api/workspaces',workspaces,undefined,cookie)).json();assert.ok(listed.workspaces.some((x:any)=>x.workspace.id===workspace.id));
  const stranger=await db.dashboardUser.create({data:{externalSubject:'test|'+suffix}});ids.push(stranger.id);
  assert.equal(await requireWorkspaceRole({userId:stranger.id,issuer:'test',subject:suffix},workspace.id,'VIEWER'),null);
  assert.equal(evaluateDashboardTrial(new Date('2028-01-31T12:00:00Z')).expiresAt,'2028-02-29T12:00:00.000Z');
  const trial=evaluateDashboardTrial(user.createdAt);assert.equal(evaluateDashboardTrial(user.createdAt,new Date(trial.expiresAt)).active,false);
  const another=await call('/api/workspaces',createWorkspace,{name:'Second Business'},cookie);assert.equal(another.status,201);
  const second=(await another.json()).workspace;workspaceIds.push(second.id);
  assert.equal((await db.dashboardWorkspace.findUniqueOrThrow({where:{id:second.id}})).trialStartedAt!.toISOString(),user.createdAt.toISOString());
  assert.equal((await call('/api/auth/password-reset',reset,{action:'request',email})).status,200);
  const resetToken=new URL(emails.at(-1)!.text.split('\n').at(-1)!).searchParams.get('token');
  assert.equal((await call('/api/auth/verify',verify,{token:resetToken})).status,400);
  const newPassword='Replacement-test-password-456';
  assert.equal((await call('/api/auth/password-reset',reset,{action:'confirm',token:resetToken,password:newPassword})).status,200);
  assert.equal(await getAuthenticatedDashboardActor(request('/api/workspaces',undefined,cookie)),null);
  assert.equal((await call('/api/auth/password-login',login,{email,password:newPassword})).status,200);
  assert.equal((await call('/api/auth/password-login',login,{email,password})).status,401);
  assert.equal((await call('/api/auth/password-reset',reset,{action:'confirm',token:resetToken,password:newPassword})).status,400);
  emailFailure=true;
  const failedEmail='failure-'+suffix+'@example.test';
  assert.equal((await call('/api/auth/signup',signup,{name:'Test Failure',email:failedEmail,password})).status,503);
  assert.equal(await db.dashboardUser.count({where:{email:failedEmail}}),0);
 }finally{
  globalThis.fetch=originalFetch;
  for(const key of Object.keys(process.env))if(!(key in saved))delete process.env[key];
  Object.assign(process.env,saved);
  await db.dashboardWorkspace.deleteMany({where:{id:{in:workspaceIds}}});
  await db.dashboardUser.deleteMany({where:{id:{in:ids}}});
  await db.$disconnect();
 }
});
